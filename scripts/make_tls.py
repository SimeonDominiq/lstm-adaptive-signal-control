"""
Generate the SUMO traffic-light programme for the modelled intersection.

Link indices are assigned by netconvert, not declared by us, so this script
reads the built network, works out which link index belongs to which of the
eight movements, and generates the phase state strings from that. The mapping
is written to network/movement_map.json for the controllers to reuse, so every
part of the system agrees on which index is which movement.

Run AFTER building the network:
    bash network/build_network.sh
    python3 scripts/make_tls.py

Lane convention (see network/edges.edg.xml and connections.con.xml):
    lane 1 = dedicated left turn
    lane 0 = shared through / right

Movements (one per approach lane, eight in total):
    S2C lane1 = NB_L    S2C lane0 = NB_TR
    N2C lane1 = SB_L    N2C lane0 = SB_TR
    W2C lane1 = EB_L    W2C lane0 = EB_TR
    E2C lane1 = WB_L    E2C lane0 = WB_TR

Four protected phases (eight movements -> four phases):
    P1  NS through/right    NB_TR, SB_TR
    P2  NS left             NB_L,  SB_L
    P3  EW through/right    EB_TR, WB_TR
    P4  EW left             EB_L,  WB_L

Timing (Chapter Three): 140 s cycle = 120 s green + 20 s intergreen,
intergreen = 4 x (3 s yellow + 2 s all-red). Greens bounded 10-60 s.
"""

import json
import os
import xml.etree.ElementTree as ET

YELLOW = 3
ALLRED = 2
CYCLE = 140
GREEN_TOTAL = 120
G_MIN, G_MAX = 10, 60
TLS_ID = "C"

LANE_TO_MOVEMENT = {
    ("S2C", 1): "NB_L",  ("S2C", 0): "NB_TR",
    ("N2C", 1): "SB_L",  ("N2C", 0): "SB_TR",
    ("W2C", 1): "EB_L",  ("W2C", 0): "EB_TR",
    ("E2C", 1): "WB_L",  ("E2C", 0): "WB_TR",
}

MOVEMENTS = ["NB_L", "NB_TR", "SB_L", "SB_TR", "EB_L", "EB_TR", "WB_L", "WB_TR"]

PHASE_NAMES = ["NS_through_right", "NS_left", "EW_through_right", "EW_left"]
PHASE_MOVEMENTS = [
    ["NB_TR", "SB_TR"],
    ["NB_L", "SB_L"],
    ["EB_TR", "WB_TR"],
    ["EB_L", "WB_L"],
]


def read_network(net_path):
    """Return movement -> sorted link indices, all indices, and any unmapped links."""
    if not os.path.exists(net_path):
        raise SystemExit(
            f"network not found: {net_path}\n"
            "Build it first:  bash network/build_network.sh")

    root = ET.parse(net_path).getroot()
    movement_links = {m: [] for m in MOVEMENTS}
    all_indices = []
    unmapped = []

    for conn in root.findall("connection"):
        if conn.get("tl") != TLS_ID:
            continue
        raw = conn.get("linkIndex")
        if raw is None:
            continue
        idx = int(raw)
        all_indices.append(idx)
        key = (conn.get("from"), int(conn.get("fromLane")))
        mv = LANE_TO_MOVEMENT.get(key)
        if mv is None:
            unmapped.append((key, idx, conn.get("to")))
        else:
            movement_links[mv].append(idx)

    for m in movement_links:
        movement_links[m].sort()
    return movement_links, sorted(all_indices), unmapped


def state(active, n_links, char="G"):
    s = ["r"] * n_links
    for i in active:
        s[i] = char
    return "".join(s)


def build_phases(green_times, movement_links, n_links):
    if len(green_times) != 4:
        raise ValueError("need exactly four green times")
    for g in green_times:
        if not (G_MIN <= g <= G_MAX):
            raise ValueError(f"green {g}s outside bounds {G_MIN}-{G_MAX}s")
    phases = []
    for i, g in enumerate(green_times):
        links = []
        for mv in PHASE_MOVEMENTS[i]:
            links.extend(movement_links[mv])
        phases.append((g, state(links, n_links, "G"), f"{PHASE_NAMES[i]}_green"))
        phases.append((YELLOW, state(links, n_links, "y"), f"{PHASE_NAMES[i]}_yellow"))
        phases.append((ALLRED, state([], n_links, "r"), f"{PHASE_NAMES[i]}_allred"))
    return phases


def write_tls(phases, path, program_id="fixed_equal"):
    total = sum(p[0] for p in phases)
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!-- Generated by scripts/make_tls.py from the built network. Do not edit by hand. -->",
        f"<!-- total cycle {total}s -->",
        '<additional xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
        '            xsi:noNamespaceSchemaLocation="http://sumo.dlr.de/xsd/additional_file.xsd">',
        f'    <tlLogic id="{TLS_ID}" type="static" programID="{program_id}" offset="0">',
    ]
    for dur, st, name in phases:
        lines.append(f'        <phase duration="{dur}" state="{st}" name="{name}"/>')
    lines += ["    </tlLogic>", "</additional>", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))
    return total



def patch_net(net_path, phases, program_id="0"):
    """
    Replace the tlLogic that netconvert generated inside the network file with
    our own programme, keeping the same programID so it remains the active one.

    netconvert always writes a default programme with programID "0". Loading a
    second programme with that same id from an additional file is an error, so
    the specified plan is written into the network instead. This also means a
    plain `sumo -c` run uses the 140 s cycle without any further setup.

    Re-running netconvert overwrites the network, so make_tls.py must be re-run
    after it - which is the documented build order.
    """
    ET.register_namespace("xsi", "http://www.w3.org/2001/XMLSchema-instance")
    tree = ET.parse(net_path)
    root = tree.getroot()

    target = None
    for tl in root.findall("tlLogic"):
        if tl.get("id") == TLS_ID and tl.get("programID") == program_id:
            target = tl
            break
    if target is None:
        raise SystemExit(
            f"no tlLogic id={TLS_ID} programID={program_id} found in {net_path}")

    for child in list(target):
        target.remove(child)
    target.set("type", "static")
    target.set("offset", "0")
    for dur, st, name in phases:
        ph = ET.SubElement(target, "phase")
        ph.set("duration", str(dur))
        ph.set("state", st)
        ph.set("name", name)

    tree.write(net_path, encoding="UTF-8", xml_declaration=True)
    return sum(p[0] for p in phases)


def main():
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    net_path = os.path.join(here, "network", "intersection.net.xml")

    movement_links, all_idx, unmapped = read_network(net_path)
    n_links = (max(all_idx) + 1) if all_idx else 0

    print(f"Read {net_path}")
    print(f"  traffic-light links found : {len(all_idx)}  (state string length {n_links})")

    ok = True
    if unmapped:
        print("  FAIL: connections not recognised as one of the eight movements:")
        for key, idx, to in unmapped:
            print(f"     {key} -> {to} (linkIndex {idx})")
        ok = False

    print("\n  movement -> link indices")
    for m in MOVEMENTS:
        links = movement_links[m]
        print(f"     {m:<6} {links}")
        if not links:
            print(f"     FAIL: movement {m} has no controlled link")
            ok = False

    covered = sorted(i for links in movement_links.values() for i in links)
    if covered != all_idx:
        print(f"\n  FAIL: link coverage mismatch\n     mapped     {covered}\n     in network {all_idx}")
        ok = False
    else:
        print(f"\n  PASS: all {len(all_idx)} links map to exactly one movement")

    seen = {}
    for i, movs in enumerate(PHASE_MOVEMENTS):
        for mv in movs:
            for link in movement_links[mv]:
                if link in seen:
                    print(f"  FAIL: link {link} green in phases {seen[link]} and {i}")
                    ok = False
                seen[link] = i
    if ok and len(seen) == len(all_idx):
        print("  PASS: every link is green in exactly one phase")

    if not ok:
        raise SystemExit("\nchecks failed - not writing the programme")

    equal = [GREEN_TOTAL // 4] * 4
    phases = build_phases(equal, movement_links, n_links)
    total = sum(p[0] for p in phases)
    if total != CYCLE:
        raise SystemExit(f"FAIL: cycle is {total}s, expected {CYCLE}s")
    print(f"  PASS: equal split {equal} gives a {total}s cycle "
          f"({GREEN_TOTAL}s green + {4*(YELLOW+ALLRED)}s intergreen)")

    print("\n  phase states")
    for dur, st, name in phases:
        print(f"     {dur:>3}s  {st}  {name}")

    out = os.path.join(here, "network", "tls_fixed_equal.add.xml")
    write_tls(phases, out)
    print(f"\n  wrote {out}  (programID 'fixed_equal', for TraCI use)")

    patch_net(net_path, phases, program_id="0")
    print(f"  patched {net_path}  (programID '0' replaced with the 140s plan)")

    mapping = dict(
        tls_id=TLS_ID, n_links=n_links, cycle=CYCLE,
        green_total=GREEN_TOTAL, yellow=YELLOW, allred=ALLRED,
        g_min=G_MIN, g_max=G_MAX,
        movements=MOVEMENTS,
        movement_links=movement_links,
        phase_names=PHASE_NAMES,
        phase_movements=PHASE_MOVEMENTS,
        phase_links=[sorted(i for mv in movs for i in movement_links[mv])
                     for movs in PHASE_MOVEMENTS],
    )
    mpath = os.path.join(here, "network", "movement_map.json")
    with open(mpath, "w") as f:
        json.dump(mapping, f, indent=2)
    print(f"  wrote {mpath}  (used by the controllers)")


if __name__ == "__main__":
    main()
